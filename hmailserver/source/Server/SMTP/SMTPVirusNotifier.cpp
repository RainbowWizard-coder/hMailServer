   void
   SMTPVirusNotifier::CreateMessageDeletedNotification(const std::shared_ptr<Message> pOriginalMessage, const String &sRecipient, const String &sAddressedTo)
   {
      // A notice to nobody: the notice to the sender of a message whose envelope
      // sender is empty - a bounce - has no place to go. Asked of the address the
      // notice is for, not of the message's sender: a recipient of such a message
      // has an address all the same, and is told as any other recipient is.
      // Asked before the file is read, as well as below.
      if (sRecipient.IsEmpty())
         return;

      // Parse out the subject in the original message, so that we can Re: that.
      CreateMessageDeletedNotification(pOriginalMessage, sRecipient, sAddressedTo,
         PersistentMessage::LoadHeader(MessageStore::WorkingFile(pOriginalMessage)));
   }

   void
   SMTPVirusNotifier::CreateMessageDeletedNotification(const std::shared_ptr<Message> pOriginalMessage, const String &sRecipient, const String &sAddressedTo, const AnsiString &originalHeader)
   {
      LOG_DEBUG("SMTPVirusNotifier::CreateMessageDeletedNotification");

      if (sRecipient.IsEmpty())
         return;

      MimeHeader header;
      header.Load(originalHeader, originalHeader.GetLength(), true);

      String sMailerDaemonAddress = MailerDaemonAddressDeterminer::GetMailerDaemonAddress(pOriginalMessage);

      String sTextVirusFound = Configuration::Instance()->GetServerMessages()->GetMessage("VIRUS_FOUND");
      String sErrMsg = Configuration::Instance()->GetServerMessages()->GetMessage("VIRUS_NOTIFICATION");

      String sOriginalSubject = header.GetRawFieldValue("Subject");
      String sOriginalFrom = header.GetRawFieldValue("From");
      String sOriginalTo = header.GetRawFieldValue("To");

      // A header with nothing in it: the message's file could not be read when
      // the header was asked for - another program held it or had taken it away.
      // That is how the strip action comes to delete a message it cannot read,
      // and it can happen to the delete action's notices too, which read the
      // file as they are made. Every field of the notice was then empty, and
      // whoever it went to could not tell which message had been deleted. The
      // envelope says who sent it, or that nobody did. Whom it was sent to is
      // the caller's to say, since the notice may be going to a recipient or to
      // the sender: a recipient's notice names that recipient alone, and the
      // sender's each address the message was taken for, before it was
      // resolved (MessageRecipients::GetCommaSeparatedOriginalAddresses).
      if (header.GetFieldCount() == 0)
      {
         sOriginalFrom = pOriginalMessage->GetFromAddress().IsEmpty() ? String(_T("<>")) : pOriginalMessage->GetFromAddress();
         sOriginalTo = sAddressedTo;
      }

      // Replace macros.
      sErrMsg.Replace(_T("%MACRO_FROM%"), sOriginalFrom);
      sErrMsg.Replace(_T("%MACRO_TO%"), sOriginalTo);
      sErrMsg.Replace(_T("%MACRO_SENT%"), String(header.GetRawFieldValue("Date")));
      sErrMsg.Replace(_T("%MACRO_SUBJECT%"), sOriginalSubject);

      // Send a notification
      std::shared_ptr<Message> pMsg = std::shared_ptr<Message>(new Message());

      pMsg->SetState(Message::Delivering);

      std::shared_ptr<Account> account;

      std::shared_ptr<MessageData> pNewMsgData = std::shared_ptr<MessageData>(new MessageData());
      pNewMsgData->LoadFromMessage(account, pMsg);

      // Required headers
      pNewMsgData->GenerateMessageID();
      pNewMsgData->SetSentTime(Time::GetCurrentMimeDate());

      // Optional headers
      pNewMsgData->SetFrom(sMailerDaemonAddress);
      pNewMsgData->SetTo(sRecipient);
      pNewMsgData->SetSubject(sTextVirusFound + ": " + sOriginalSubject);
      pNewMsgData->SetBody(sErrMsg);
      pNewMsgData->SetAutoGenerated();
      pNewMsgData->IncreaseRuleLoopCount();

      // Write message data. First write of a message built from nothing - see the
      // equivalent in SMTPDeliverer.
      if (!pNewMsgData->WriteReported(MessageStore::WorkingFile(pMsg), "A virus notification"))
         return;

      // Add recipients.
      bool recipientOK = false;
      RecipientParser recipientParser;
      recipientParser.CreateMessageRecipientList(sRecipient, pMsg->GetRecipients(), recipientOK);

      // Save message. As in SMTPVacationMessageCreator: the WriteReported above was
      // checked and this was not, which leaves the other half of the same pair open.
      if (pMsg->GetRecipients()->GetCount() > 0)
      {
         if (!PersistentMessage::SaveObject(pMsg))
         {
            FileUtilities::DeleteFile(MessageStore::WorkingFile(pMsg));

            ErrorManager::Instance()->ReportError(ErrorManager::Medium, 6090, "SMTPVirusNotifier::CreateMessageDeletedNotification",
               "The virus notification could not be saved and has not been sent, so nobody has been told that a message was deleted. Its file has been removed rather than left on disk with nothing referring to it.");
         }
      }

      // Tell app to submit mail
      Application::Instance()->SubmitPendingEmail();  

      LOG_DEBUG("SMTPVirusNotifier::~CreateMessageDeletedNotification");
   }
