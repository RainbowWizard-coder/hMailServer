      [Test]
      [Description("The endpoint must be https, or plain http to a literal loopback address; a refused one leaves the stored value and asks nothing")]
      public void TheEndpointMustBeHttpsOrLoopback()
      {
         using (var corpus = new FakeBreachCorpus())
         {
            string[] refused =
            {
               "http://example.com/range/",
               "http://127.evil.example/range/",
               "https://user@mirror.example/range/",
               "https://mirror.example/range/#x",
               "https://mirror.example/range/?a=1",
               ""
            };

            string[] accepted =
            {
               "https://mirror.example/range/",
               "http://127.0.0.1:9551/range/",
               "http://localhost:9551/range/",
               "http://[::1]:9551/range/",
               "https://mirror.example/p/{prefix}.txt"
            };

            Set("BreachCheckUrl", FakeBreachCorpus.Url);

            foreach (string url in refused)
            {
               Assert.Throws<COMException>(() => Set("BreachCheckUrl", url), "Must be refused: '" + url + "'");
               ClassicAssert.AreEqual(FakeBreachCorpus.Url, Convert.ToString(Get("BreachCheckUrl")), "A refused endpoint changed the stored one: '" + url + "'");
            }

            foreach (string url in accepted)
            {
               Set("BreachCheckUrl", url);
               ClassicAssert.AreEqual(url, Convert.ToString(Get("BreachCheckUrl")), "Must be accepted and read back: '" + url + "'");
            }

            ClassicAssert.AreEqual(0, corpus.Requests.Count, "Storing an endpoint must not ask it anything.");
         }
      }

      [Test]
      [Description("A chosen app password is checked; a generated one is not asked about")]
      public void ChosenAppPasswordsAreCheckedAndGeneratedOnesAreNot()
      {
         const string leaked = "correct horse battery staple";
         var account = NewAccount("breachapp", "Original-Password-9551");

         AppPasswords passwords;
         try
         {
            passwords = account.AppPasswords;
         }
         catch (COMException ex) when ((uint) ex.ErrorCode == 0x80040155)
         {
            Assert.Ignore("The app-password COM interfaces are not registered on this machine. Run 'hMailServer.exe /RegisterTypeLib' from an elevated prompt. " + ex.Message);
            return;
         }

         using (var corpus = new FakeBreachCorpus())
         {
            corpus.Add(leaked, 1200);
            Enable(FakeBreachCorpus.Url);

            AppPassword chosen = passwords.Add();
            chosen.Name = "Chosen";
            var ex = Assert.Throws<COMException>(() => chosen.SetPassword(leaked), "A chosen app password in the corpus must be refused.");
            StringAssert.Contains(BreachedSentence, ex.Message);
            ClassicAssert.AreEqual(1, corpus.Requests.Count);

            // Negative control: a chosen secret the corpus does not hold.
            chosen.SetPassword("an app password nobody has 9551");
            chosen.Save();
            ClassicAssert.AreEqual(2, corpus.Requests.Count);

            AppPassword generated = passwords.Add();
            generated.Name = "Generated";
            generated.Generate();
            generated.Save();
            ClassicAssert.AreEqual(2, corpus.Requests.Count, "A generated app password is random and nobody's; it must not be asked about.");
         }
      }

      [Test]
      [Description("The administrator password is checked, and a refusal leaves the suite's credential working")]
      public void TheAdministratorPasswordIsChecked()
      {
         const string leaked = "administrator-password-in-corpus";

         using (var corpus = new FakeBreachCorpus())
         {
            corpus.Add(leaked, 55);
            Enable(FakeBreachCorpus.Url);

            try
            {
               var ex = Assert.Throws<COMException>(() => _settings.SetAdministratorPassword(leaked));
               StringAssert.Contains(BreachedSentence, ex.Message);

               ClassicAssert.IsNotNull(new hMailServer.Application().Authenticate("Administrator", AdminPassword),
                  "The refused change must leave the administrator password as it was.");

               // Negative control: one the corpus does not hold is accepted.
               const string fresh = "an administrator password nobody has 9551";
               _settings.SetAdministratorPassword(fresh);
               ClassicAssert.IsNotNull(new hMailServer.Application().Authenticate("Administrator", fresh),
                  "The accepted administrator password must be the one in force.");
               ClassicAssert.AreEqual(2, corpus.Requests.Count);
            }
            finally
            {
               Set("BreachCheckEnabled", false);
               _settings.SetAdministratorPassword(AdminPassword);
            }
         }
      }

      [Test]
      [Description("The local rules decide first and cost no request, and a breach refusal records no history")]
      public void TheLocalRulesRefuseBeforeTheNetworkIsAsked()
      {
         var account = NewAccount("breachlocal", "First-Password-9551");

         ServerIniFile.SetSetting("PasswordPolicyMinimumLength", "16");
         ServerIniFile.SetSetting("PasswordPolicyHistoryCount", "1");
         _application.Reinitialize();

         using (var corpus = new FakeBreachCorpus())
         {
            corpus.Add("a-leaked-but-long-password", 99);
            Enable(FakeBreachCorpus.Url);

            ClassicAssert.IsNotNull(Refusal(account, "short"), "The policy refuses a short password.");
            ClassicAssert.AreEqual(0, corpus.Requests.Count, "A password the policy refuses must cost no request.");

            ClassicAssert.IsNotNull(Refusal(account, "First-Password-9551"), "The reuse history refuses the current password.");
            ClassicAssert.AreEqual(0, corpus.Requests.Count, "A password the history refuses must cost no request.");

            // First -> Second: the history now holds First (a depth of one).
            ClassicAssert.IsNull(Refusal(account, "Second-Password-9551"));
            ClassicAssert.AreEqual(1, corpus.Requests.Count);

            // A breach refusal. Had it recorded the history - Second pushed in, First
            // trimmed out at a depth of one - First would be accepted below.
            ClassicAssert.IsNotNull(Refusal(account, "a-leaked-but-long-password"));
            ClassicAssert.AreEqual(2, corpus.Requests.Count);

            string refusal = Refusal(account, "First-Password-9551");
            ClassicAssert.IsNotNull(refusal,
               "First is still the one password in the history, so it must be refused as recently used. Accepted means the breach refusal recorded history.");
            StringAssert.Contains("used recently", refusal);
         }
      }

