               // Negative control: one the corpus does not hold is accepted.
               const string fresh = "an administrator password nobody has 9551";
               _settings.SetAdministratorPassword(fresh);
               ClassicAssert.IsNotNull(new hMailServer.Application().Authenticate("Administrator", fresh),
                  "The accepted administrator password must be the one in force.");
               ClassicAssert.AreEqual(2, corpus.Requests.Count);
            }
            finally
            {
               Set("BreachCheckEnabled", false);
               _settings.SetAdministratorPassword(AdminPassword);
            }
         }
      }

      [Test]
      [Description("The local rules decide first and cost no request, and a breach refusal records no history")]
      public void TheLocalRulesRefuseBeforeTheNetworkIsAsked()
      {
         var account = NewAccount("breachlocal", "First-Password-9551");

         ServerIniFile.SetSetting("PasswordPolicyMinimumLength", "16");
         ServerIniFile.SetSetting("PasswordPolicyHistoryCount", "1");
         _application.Reinitialize();

         using (var corpus = new FakeBreachCorpus())
         {
            corpus.Add("a-leaked-but-long-password", 99);
            Enable(FakeBreachCorpus.Url);

            ClassicAssert.IsNotNull(Refusal(account, "short"), "The policy refuses a short password.");
            ClassicAssert.AreEqual(0, corpus.Requests.Count, "A password the policy refuses must cost no request.");

            ClassicAssert.IsNotNull(Refusal(account, "First-Password-9551"), "The reuse history refuses the current password.");
            ClassicAssert.AreEqual(0, corpus.Requests.Count, "A password the history refuses must cost no request.");

            // First -> Second: the history now holds First (a depth of one).
            ClassicAssert.IsNull(Refusal(account, "Second-Password-9551"));
            ClassicAssert.AreEqual(1, corpus.Requests.Count);

            // A breach refusal. Had it recorded the history - Second pushed in, First
            // trimmed out at a depth of one - First would be accepted below.
            ClassicAssert.IsNotNull(Refusal(account, "a-leaked-but-long-password"));
            ClassicAssert.AreEqual(2, corpus.Requests.Count);

