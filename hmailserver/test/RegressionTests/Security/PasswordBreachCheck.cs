      [Test]
      [Description("Off by default: a password in the corpus is accepted, and the endpoint is asked nothing")]
      public void OffByDefaultSendsNothing()
      {
         using (var corpus = new FakeBreachCorpus())
         {
            corpus.Add("password", 10434004);

            // Pointed at the fake and left switched off, so that a check running
            // regardless of the switch would be seen asking.
            Set("BreachCheckUrl", FakeBreachCorpus.Url);

            var account = NewAccount("breachoff", "initial-password-9551");

            ClassicAssert.IsNull(Refusal(account, "password"),
               "The check is off by default; an upgrade must not start refusing passwords, nor sending anything anywhere.");
            ClassicAssert.AreEqual(0, corpus.Requests.Count, "A switched-off check sent a request.");
         }
      }

      [Test]
      [Description("The four settings exist with their defaults, so no reader meets a missing row")]
      public void DefaultsReadBack()
      {
         ClassicAssert.AreEqual(false, Convert.ToBoolean(Get("BreachCheckEnabled")));
         ClassicAssert.AreEqual("https://api.pwnedpasswords.com/range/", Convert.ToString(Get("BreachCheckUrl")));
         ClassicAssert.AreEqual(1, Convert.ToInt32(Get("BreachCheckMinimumCount")));
         ClassicAssert.AreEqual(0, Convert.ToInt32(Get("BreachCheckUnreachableAction")));

         // And what is written is what is read, which is how an editor shows its own state.
         Enable(FakeBreachCorpus.Url, 7, 1);
         ClassicAssert.AreEqual(true, Convert.ToBoolean(Get("BreachCheckEnabled")));
         ClassicAssert.AreEqual(FakeBreachCorpus.Url, Convert.ToString(Get("BreachCheckUrl")));
         ClassicAssert.AreEqual(7, Convert.ToInt32(Get("BreachCheckMinimumCount")));
         ClassicAssert.AreEqual(1, Convert.ToInt32(Get("BreachCheckUnreachableAction")));
      }

      [Test]
      [Description("What leaves the server is GET /range/5BAA6 with Add-Padding for the password \"password\" - never the password, the hash or the suffix")]
      public void TheKnownPrefixOfAKnownPasswordIsWhatLeaves()
      {
         ClassicAssert.AreEqual(PasswordHash, FakeBreachCorpus.Sha1HexUtf8("password"), "The fixture's own SHA-1 disagrees with the published vector.");

         using (var corpus = new FakeBreachCorpus())
         {
            corpus.Add("password", 10434004);
            Enable(FakeBreachCorpus.Url);

            var account = NewAccount("breachwire", "initial-password-9551");
            string refusal = Refusal(account, "password");

            ClassicAssert.IsNotNull(refusal, "\"password\" is in the corpus and must be refused.");
            ClassicAssert.AreEqual(1, corpus.Requests.Count, "Exactly one request for one password change.");

            string request = corpus.Requests[0];
            StringAssert.StartsWith("GET /range/" + PasswordPrefix + " HTTP/1.0\r\n", request, "The request line carries the five-character prefix: " + request);
            StringAssert.Contains("\r\nAdd-Padding: true\r\n", request, "The request must ask for padding: " + request);

            StringAssert.DoesNotContain("password", request, "The password left the server: " + request);
            StringAssert.DoesNotContain(PasswordHash, request, "The whole hash left the server: " + request);
            StringAssert.DoesNotContain(PasswordSuffix, request, "The suffix left the server: " + request);
            StringAssert.DoesNotContain(PasswordHash.ToLowerInvariant(), request, "The whole hash left the server in lower case: " + request);
         }
      }

