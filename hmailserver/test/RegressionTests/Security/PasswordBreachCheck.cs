      [Test]
      [Description("The minimum count is a boundary: seen three times is refused at three and accepted at four")]
      public void TheMinimumCountIsABoundary()
      {
         const string password = "seen-exactly-three-times";

         using (var corpus = new FakeBreachCorpus())
         {
            corpus.Add(password, 3);
            var account = NewAccount("breachminimum", "Original-Password-9551");

            Enable(FakeBreachCorpus.Url, 3);
            ClassicAssert.IsNotNull(Refusal(account, password), "Seen three times with a minimum of three: refused.");

            Enable(FakeBreachCorpus.Url, 4);
            ClassicAssert.IsNull(Refusal(account, password), "Seen three times with a minimum of four: accepted.");

            // A minimum below one is refused rather than stored.
            Assert.Throws<COMException>(() => Set("BreachCheckMinimumCount", 0));
            ClassicAssert.AreEqual(4, Convert.ToInt32(Get("BreachCheckMinimumCount")), "A refused minimum must leave the stored one.");
         }
      }

      [Test]
