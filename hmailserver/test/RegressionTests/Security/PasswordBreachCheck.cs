      [Test]
      [Description("TestBreachCheckEndpoint asks for 00000 and reports the entries; one that cannot be used is an error with the reason")]
      public void TheEndpointTestReportsWhatItFound()
      {
         using (var corpus = new FakeBreachCorpus())
         {
            corpus.AddHash("00000" + "1E4C9B93F3F0682250B6CF8331B7EE68FD8", 4);

            int entries = TestEndpoint(FakeBreachCorpus.Url);
            ClassicAssert.AreEqual(4, entries, "One real entry and three padding entries.");
            ClassicAssert.AreEqual(1, corpus.Requests.Count);
            StringAssert.StartsWith("GET /range/00000 HTTP/1.0\r\n", corpus.Requests[0]);
            ClassicAssert.AreEqual(false, Convert.ToBoolean(Get("BreachCheckEnabled")), "Testing an endpoint must not switch the check on.");
         }

         var unreachable = Assert.Throws<COMException>(() => TestEndpoint(FakeBreachCorpus.Url), "Nothing listens on 9551 now.");
         StringAssert.Contains("127.0.0.1", unreachable.Message, "The reason names the host that could not be reached. Got: " + unreachable.Message);

         Assert.Throws<COMException>(() => TestEndpoint("http://example.com/range/"), "An endpoint the check would not accept is not asked.");
      }
