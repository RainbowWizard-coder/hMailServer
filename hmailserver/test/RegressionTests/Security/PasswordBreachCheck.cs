      [Test]
      [Description("What leaves the server is GET /range/5BAA6 with Add-Padding for the password \"password\" - never the password, the hash or the suffix")]
      public void TheKnownPrefixOfAKnownPasswordIsWhatLeaves()
      {
         ClassicAssert.AreEqual(PasswordHash, FakeBreachCorpus.Sha1HexUtf8("password"), "The fixture's own SHA-1 disagrees with the published vector.");

         using (var corpus = new FakeBreachCorpus())
         {
            corpus.Add("password", 10434004);

            // The account is made before the check is switched on, as it is in every
            // other test here: an account's own password is a password choice like any
            // other, and InterfaceAccount::put_Password asks the corpus about it - so
            // with the check already on, creating the account costs a request of its
            // own and "exactly one request for one change" counts two.
            var account = NewAccount("breachwire", "initial-password-9551");
            Enable(FakeBreachCorpus.Url);

            string refusal = Refusal(account, "password");

            ClassicAssert.IsNotNull(refusal, "\"password\" is in the corpus and must be refused.");
            ClassicAssert.AreEqual(1, corpus.Requests.Count, "Exactly one request for one password change.");

            string request = corpus.Requests[0];
            StringAssert.StartsWith("GET /range/" + PasswordPrefix + " HTTP/1.0\r\n", request, "The request line carries the five-character prefix: " + request);
            StringAssert.Contains("\r\nAdd-Padding: true\r\n", request, "The request must ask for padding: " + request);
            StringAssert.Contains("\r\nHost: 127.0.0.1:" + FakeBreachCorpus.Port + "\r\n", request, "The Host header names the endpoint's port, which is not 80: " + request);

            StringAssert.DoesNotContain("password", request, "The password left the server: " + request);
            StringAssert.DoesNotContain(PasswordHash, request, "The whole hash left the server: " + request);
            StringAssert.DoesNotContain(PasswordSuffix, request, "The suffix left the server: " + request);
            StringAssert.DoesNotContain(PasswordHash.ToLowerInvariant(), request, "The whole hash left the server in lower case: " + request);
         }
      }

