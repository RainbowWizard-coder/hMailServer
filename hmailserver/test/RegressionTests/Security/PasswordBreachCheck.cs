      [Test]
      [Description("The hash is SHA-1 over UTF-8: found under its UTF-8 digest, and not under its Windows-1252 or UTF-16 digests")]
      public void TheHashIsTakenOverUtf8()
      {
         const string password = "pässwörd-2026";
         string utf8 = FakeBreachCorpus.Sha1HexUtf8(password);
         string ansi = FakeBreachCorpus.Sha1Hex(Encoding.GetEncoding(28591).GetBytes(password));
         string utf16 = FakeBreachCorpus.Sha1Hex(Encoding.Unicode.GetBytes(password));

         ClassicAssert.AreEqual("7DF5AB98EEEBE93B14A0AB70F4284204AC981A4B", utf8, "The fixture's UTF-8 vector moved.");

         var account = NewAccount("breachutf8", "Original-Password-9551");

         using (var corpus = new FakeBreachCorpus())
         {
            corpus.AddHash(utf8, 12);
            Enable(FakeBreachCorpus.Url);

            ClassicAssert.IsNotNull(Refusal(account, password), "The password's UTF-8 SHA-1 is in the corpus, so it must be refused.");
         }

         // Negative control: the corpus holds only the digests of the wrong encodings.
         // A server hashing the ANSI code page or UTF-16 would ask for their prefixes,
         // find them, and refuse; the right one asks for the UTF-8 prefix and finds
         // nothing.
         using (var corpus = new FakeBreachCorpus())
         {
            corpus.AddHash(ansi, 12);
            corpus.AddHash(utf16, 12);

            ClassicAssert.IsNull(Refusal(account, password),
               "Only the Windows-1252 and UTF-16 digests are in the corpus; refusing means the server hashed one of those.");
            ClassicAssert.AreEqual(1, corpus.Requests.Count);
            StringAssert.StartsWith("GET /range/" + utf8.Substring(0, 5) + " ", corpus.Requests[0], "The prefix asked for must be the UTF-8 digest's.");
         }
      }

