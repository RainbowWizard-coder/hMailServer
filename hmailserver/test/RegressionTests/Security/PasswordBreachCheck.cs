   /// <summary>
   ///    A new password checked against the published breach corpus, by the range query
   ///    of the k-anonymity model, over COM: Account.Password, AppPassword.SetPassword and
   ///    Settings.SetAdministratorPassword, and the four settings and the endpoint test
   ///    on Settings.
   ///
   ///    The corpus is FakeBreachCorpus on 127.0.0.1:9551, and nothing here reaches the
   ///    internet. What leaves the server is asserted on the request the fake received,
   ///    against the published SHA-1 of "password", so the claim "five characters and
   ///    nothing else" is tested on the wire rather than read off the code. Every
   ///    refusal has a negative control beside it - the same path with a password that
   ///    is not in the corpus, accepted - so a check that refused everything would fail.
   ///
   ///    THE SETTINGS ARE WRITTEN BY LATE BINDING, as SyslogExport writes its own: they
   ///    are new members of IInterfaceSettings, the checked-in interop is regenerated by
   ///    hand after an IDL change, and a fixture that did not compile until then would
   ///    stop the whole suite building rather than failing here.
   /// </summary>
   [TestFixture]
   public class PasswordBreachCheck : TestFixtureBase
   {
      private const string BreachedSentence = "appears in a published data breach";
      private const string UnavailableSentence = "could not be checked against published data breaches";

      // SHA-1("password"), the vector every description of the range API uses.
      private const string PasswordHash = "5BAA61E4C9B93F3F0682250B6CF8331B7EE68FD8";
      private const string PasswordPrefix = "5BAA6";
      private const string PasswordSuffix = "1E4C9B93F3F0682250B6CF8331B7EE68FD8";

      private const string AdminPassword = "testar";

      private string _proxyBefore;

      [SetUp]
      public void BreachCheckSetUp()
      {
         // The fake is on this machine's loopback address. A server on another host,
         // which the Linux suite can be pointed at, would be asking its own.
         if (TestPorts.Host != "127.0.0.1" && !string.Equals(TestPorts.Host, "localhost", StringComparison.OrdinalIgnoreCase))
            Assert.Ignore("The fake breach corpus listens on this machine's loopback address, and the server under test is on " + TestPorts.Host + ".");

         // HttpProxy applies to loopback targets too, so a bench with one left set
         // would send the fake's traffic to the proxy.
         _proxyBefore = ServerIniFile.GetSetting("HttpProxy");
         if (!string.IsNullOrEmpty(_proxyBefore))
         {
            ServerIniFile.SetSetting("HttpProxy", "");
            _application.Reinitialize();
         }

         RestoreDefaults();
      }

      [TearDown]
      public void BreachCheckTearDown()
      {
         RestoreDefaults();

         foreach (string key in new[] { "PasswordPolicyMinimumLength", "PasswordPolicyHistoryCount" })
            ServerIniFile.SetSetting(key, null);

         if (!string.IsNullOrEmpty(_proxyBefore))
            ServerIniFile.SetSetting("HttpProxy", _proxyBefore);

         _application.Reinitialize();

         // No clearing of the error log here: every test that provokes HM6600 or
         // HM6601 reads and clears the log it expects, so an error log still present
         // is one nobody expected - which the next SetUp is right to fail on.
      }

      private void RestoreDefaults()
      {
         Set("BreachCheckEnabled", false);
         Set("BreachCheckUrl", "https://api.pwnedpasswords.com/range/");
         Set("BreachCheckMinimumCount", 1);
         Set("BreachCheckUnreachableAction", 0);
      }

      // ---- late binding --------------------------------------------------------

      private void Set(string property, object value)
      {
         try
         {
            _settings.GetType().InvokeMember(property, BindingFlags.SetProperty, null, _settings, new[] { value });
         }
         catch (TargetInvocationException ex) when (ex.InnerException != null)
         {
            throw ex.InnerException;
         }
      }

      private object Get(string property)
      {
         return _settings.GetType().InvokeMember(property, BindingFlags.GetProperty, null, _settings, null);
      }

      private int TestEndpoint(string url)
      {
         try
         {
            return Convert.ToInt32(_settings.GetType().InvokeMember("TestBreachCheckEndpoint", BindingFlags.InvokeMethod, null, _settings, new object[] { url }));
         }
         catch (TargetInvocationException ex) when (ex.InnerException != null)
         {
            throw ex.InnerException;
         }
      }

      private void Enable(string url, int minimumCount = 1, int unreachableAction = 0)
      {
         Set("BreachCheckUrl", url);
         Set("BreachCheckMinimumCount", minimumCount);
         Set("BreachCheckUnreachableAction", unreachableAction);
         Set("BreachCheckEnabled", true);
      }

      private Account NewAccount(string localPart, string password)
      {
         return SingletonProvider<TestSetup>.Instance.AddAccount(_domain, localPart + "@" + _domain.Name, password);
      }

      /// <summary>The COM error text, or null when the password was taken and saved.</summary>
      private static string Refusal(Account account, string password)
      {
         try
         {
            account.Password = password;
            account.Save();
            return null;
         }
         catch (COMException ex)
         {
            return ex.Message;
         }
      }

      private static void AssertLogsOn(string address, string password, string why)
      {
         var imap = new ImapClientSimulator();
         ClassicAssert.IsTrue(imap.ConnectAndLogon(address, password), why + " (IMAP)");
         imap.Disconnect();
      }

      private static string ErrorLogWhenItSays(string code)
      {
         string log = "";
         RetryHelper.TryAction(TimeSpan.FromSeconds(10), () =>
         {
            log = LogHandler.ReadErrorLog();
            RetryableAssert.StringContains(code, log);
         });
         LogHandler.ClearErrorLogUntilSettled();
         return log;
      }

