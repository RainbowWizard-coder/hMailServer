   /// <summary>
   ///    A distribution list whose members are a query rather than a table somebody
   ///    keeps up to date: <c>DistributionList.Membership</c>, schema 6074, answered
   ///    against the server's accounts at the moment a message reaches the list.
   ///
   ///    What these tests hold the feature to:
   ///
   ///    * a <c>domain</c> query delivers to every ACTIVE account of the list's
   ///      domain and to no disabled one - the disabled account is switched back on
   ///      afterwards and found empty, because an account that cannot log on cannot
   ///      be asked whether it received anything;
   ///    * a <c>pattern:</c> query delivers to the addresses that match it and to
   ///      nothing else;
   ///    * a <c>domain:</c> query reaches another domain this server hosts, which is
   ///      the form a domain-confined credential is refused;
   ///    * the list's own recipients and the query's answers are a union
   ///      deduplicated by address - an account that is both gets exactly one copy,
   ///      and a recipient the query could never answer is still delivered to;
   ///    * moderation is untouched by a query: a sender the query does not answer
   ///      is still forwarded to the moderator and reaches no member, and a sender
   ///      the query DOES answer is a member and may post, which is the half that
   ///      proves the sender check asks the query rather than only the rows;
   ///    * a query that is none of the five forms, or that names a domain this
   ///      server does not host, is refused where it is set, and the text that is
   ///      accepted is stored in its one canonical spelling;
   ///    * a query that cannot be ANSWERED - the accounts cannot be read - refuses
   ///      the recipient with 451 rather than delivering to the list's rows and
   ///      answering 250, which is the shape a union quietly hides;
   ///    * a domain administrator may set the forms that stay inside the domains it
   ///      holds and is refused the ones that reach past them, which is the one new
   ///      authorisation decision this feature makes.
   ///
   ///    Every list and every domain here dies with the next fixture's setup, which
   ///    clears the domains before it recreates the suite's own. The one test that
   ///    makes a statement fail puts that setting back and clears the errors it
   ///    provoked whatever happens; nothing else server-wide is changed.
   /// </summary>
   [TestFixture]
   public class DistributionListQueries : TestFixtureBase
   {
      private const string Password = "test";

      /// <summary>
      ///    Whether this test asked for a database statement to fail, so that the
      ///    tear-down puts the setting back for that test and leaves the log of
      ///    every other one alone - the fixture's other tests assert that nothing
      ///    was reported, and a tear-down that deleted the log for all of them
      ///    would take that assertion away.
      /// </summary>
      private bool failureInjected_;

      [TearDown]
      public void StopSimulatingTheFailure()
      {
         if (!failureInjected_)
            return;

         failureInjected_ = false;

         IniFileSetting.Write("SimulateDatabaseFailureFor", "");
         _application.Reinitialize();

         // The injector announces itself (HM6119) for as long as it is set, and
         // the refusal being tested is an error record of its own.
         LogHandler.DeleteErrorLog();
      }

      /// <summary>
      ///    Only statements containing the fragment fail; everything else about the
      ///    session keeps working, which is what makes the refusal being tested the
      ///    one the query caused rather than a server that cannot read anything.
      ///    The setting is cached at initialisation, so Reinitialize is how it
      ///    takes - and that restarts the servers, so every connection is opened
      ///    after this call.
      /// </summary>
      private void FailStatementsContaining(string fragment)
      {
         failureInjected_ = true;
         IniFileSetting.Write("SimulateDatabaseFailureFor", fragment);
         _application.Reinitialize();
      }

      /// <summary>
      ///    Membership is reached late-bound, as QuarantineDigests reaches the
      ///    digest settings: the interop assembly is generated by tlbimp from the
      ///    type library of whatever server is REGISTERED on the machine, so a
      ///    property added to the IDL in this branch is not in the wrapper until
      ///    the built server has been registered. IDispatch asks the server that
      ///    is actually running, which is the one under test.
      /// </summary>
      private static void SetMembership(DistributionList list, string membership)
      {
         dynamic late = list;
         late.Membership = membership;
      }

      private static string GetMembership(DistributionList list)
      {
         dynamic late = list;
         return (string) late.Membership;
      }

      /// <summary>
      ///    A refusal raised by the server across IDispatch reaches here either as
      ///    the COMException itself or wrapped by the binder, so the sentence is
      ///    looked for in the whole chain rather than in the outermost message.
      /// </summary>
      private static string MessageChain(Exception thrown)
      {
         var text = thrown.Message;

         for (var inner = thrown.InnerException; inner != null; inner = inner.InnerException)
            text += " | " + inner.Message;

         return text;
      }

      private DistributionList CreateList(string address, string membership, List<string> recipients)
      {
         var list = SingletonProvider<TestSetup>.Instance.AddDistributionList(_domain, address, recipients);
         SetMembership(list, membership);
         list.Save();

         return list;
      }

      private Account AddAccount(string address)
      {
         return SingletonProvider<TestSetup>.Instance.AddAccount(_domain, address, Password);
      }

      [Test]
      [Description("A domain query delivers to every active account of the domain, and to no disabled one")]
      public void DomainQueryReachesEveryActiveAccountAndNotADisabledOne()
      {
         AddAccount("alpha@example.test");
         AddAccount("beta@example.test");
         AddAccount("poster@example.test");

         var dormant = AddAccount("dormant@example.test");
         dormant.Active = false;
         dormant.Save();

         // No recipients at all: everybody this list reaches, it reaches through
         // the query.
         CreateList("everyone@example.test", "domain", new List<string>());

         SmtpClientSimulator.StaticSend("poster@example.test", "everyone@example.test", "Notice", "Body of notice");

         ImapClientSimulator.AssertMessageCount("alpha@example.test", Password, "Inbox", 1);
         ImapClientSimulator.AssertMessageCount("beta@example.test", Password, "Inbox", 1);

         // The poster is an account of the domain, so the query answers them too:
         // a list of everybody includes whoever is writing to it.
         ImapClientSimulator.AssertMessageCount("poster@example.test", Password, "Inbox", 1);

         // The disabled account is asked only after it is switched back on, since
         // a disabled account cannot log on to be asked. Switching it on delivers
         // nothing retrospectively: had the query answered it, the copy would be
         // in its inbox already.
         dormant.Active = true;
         dormant.Save();
         ImapClientSimulator.AssertMessageCount("dormant@example.test", Password, "Inbox", 0);

         CustomAsserts.AssertNoReportedError();
      }

      [Test]
      [Description("A pattern query delivers to the addresses that match the wildcard and to nothing else")]
      public void PatternQueryReachesOnlyTheAddressesThatMatch()
      {
         AddAccount("sales-north@example.test");
         AddAccount("sales-south@example.test");
         AddAccount("support@example.test");
         AddAccount("poster@example.test");

         CreateList("sales@example.test", "pattern:sales-*@example.test", new List<string>());

         SmtpClientSimulator.StaticSend("poster@example.test", "sales@example.test", "Numbers", "Body of numbers");

         ImapClientSimulator.AssertMessageCount("sales-north@example.test", Password, "Inbox", 1);
         ImapClientSimulator.AssertMessageCount("sales-south@example.test", Password, "Inbox", 1);

         // support does not match sales-*, and neither does the poster.
         ImapClientSimulator.AssertMessageCount("support@example.test", Password, "Inbox", 0);
         ImapClientSimulator.AssertMessageCount("poster@example.test", Password, "Inbox", 0);

         CustomAsserts.AssertNoReportedError();
      }

      [Test]
      [Description("A domain: query reaches the accounts of another domain this server hosts")]
      public void NamedDomainQueryReachesTheOtherDomainsAccounts()
      {
         AddAccount("poster@example.test");
         AddAccount("alpha@example.test");

         var other = SingletonProvider<TestSetup>.Instance.AddDomain("other.test");
         SingletonProvider<TestSetup>.Instance.AddAccount(other, "contractor@other.test", Password);

         CreateList("partners@example.test", "domain:other.test", new List<string>());

         SmtpClientSimulator.StaticSend("poster@example.test", "partners@example.test", "Across", "Body across");

         ImapClientSimulator.AssertMessageCount("contractor@other.test", Password, "Inbox", 1);

         // The list's own domain is not the queried one, so nobody there is a
         // member of it.
         ImapClientSimulator.AssertMessageCount("alpha@example.test", Password, "Inbox", 0);
         ImapClientSimulator.AssertMessageCount("poster@example.test", Password, "Inbox", 0);

         CustomAsserts.AssertNoReportedError();
      }

      [Test]
      [Description("The recipients and the query are a union: an address that is both gets one copy")]
      public void RecipientsAndQueryAreOneUnionDeduplicatedByAddress()
      {
         AddAccount("alpha@example.test");
         AddAccount("beta@example.test");
         AddAccount("poster@example.test");

         var other = SingletonProvider<TestSetup>.Instance.AddDomain("other.test");
         SingletonProvider<TestSetup>.Instance.AddAccount(other, "contractor@other.test", Password);

         // alpha is a recipient AND an answer to the query; the contractor is a
         // recipient this domain's query could never answer, which is why the
         // rows still exist on a query list.
         var recipients = new List<string> {"alpha@example.test", "contractor@other.test"};

         CreateList("team@example.test", "domain", recipients);

         SmtpClientSimulator.StaticSend("poster@example.test", "team@example.test", "Once", "Body sent once");

         // One copy, not two: the expansion keeps one entry per address.
         ImapClientSimulator.AssertMessageCount("alpha@example.test", Password, "Inbox", 1);
         ImapClientSimulator.AssertMessageCount("beta@example.test", Password, "Inbox", 1);
         ImapClientSimulator.AssertMessageCount("poster@example.test", Password, "Inbox", 1);

         // And the row the query cannot answer is delivered to all the same.
         ImapClientSimulator.AssertMessageCount("contractor@other.test", Password, "Inbox", 1);

         CustomAsserts.AssertNoReportedError();
      }

      [Test]
      [Description("A sender the query answers is a member and may post to a membership-mode query list")]
      public void ASenderTheQueryAnswersMayPostToAMembershipList()
      {
         AddAccount("team-one@example.test");
         AddAccount("team-two@example.test");

         var list = CreateList("board@example.test", "pattern:team-*@example.test", new List<string>());
         list.Mode = eDistributionListMode.eLMMembership;
         list.Save();

         // team-one is not a recipient row of this list. It is a member only
         // because the query answers it, so this send proves the sender check
         // asks the query.
         SmtpClientSimulator.StaticSend("team-one@example.test", "board@example.test", "Agenda", "Body of agenda");

         ImapClientSimulator.AssertMessageCount("team-two@example.test", Password, "Inbox", 1);
         ImapClientSimulator.AssertMessageCount("team-one@example.test", Password, "Inbox", 1);

         CustomAsserts.AssertNoReportedError();
      }

      [Test]
      [Description("Moderation still applies to a query list: a sender outside the query reaches the moderator, not the members")]
      public void ModerationStillAppliesToAQueryList()
      {
         AddAccount("team-one@example.test");
         AddAccount("moderator@example.test");
         AddAccount("outsider@example.test");

         var list = CreateList("council@example.test", "pattern:team-*@example.test", new List<string>());
         list.Mode = eDistributionListMode.eLMMembership;
         list.ModeratorAddress = "moderator@example.test";
         list.Save();

         // outsider is an account of this domain, but the pattern does not answer
         // it and it is not a row: membership mode would 550 it, and with a
         // moderator set the posting goes to the moderator instead.
         SmtpClientSimulator.StaticSend("outsider@example.test", "council@example.test", "Please approve",
            "Body of posting");

         var moderatorCopy = Pop3ClientSimulator.AssertGetFirstMessageText("moderator@example.test", Password);

         Assert.IsTrue(moderatorCopy.Contains("X-hMailServer-Moderation: council@example.test"), moderatorCopy);
         Assert.IsTrue(moderatorCopy.Contains("Subject: Please approve"), moderatorCopy);

         // The member the query answers saw nothing: this waits for the delivery
         // queue to drain first, so a copy in flight would still be caught.
         ImapClientSimulator.AssertMessageCount("team-one@example.test", Password, "Inbox", 0);

         CustomAsserts.AssertNoReportedError();
      }

      [Test]
      [Description("A membership that is none of the five forms, or that names a domain this server does not host, is refused")]
      public void AQueryThatIsNotOneOfTheFormsIsRefusedWhereItIsSet()
      {
         AddAccount("alpha@example.test");

         var list = SingletonProvider<TestSetup>.Instance.AddDistributionList(_domain, "refused@example.test",
            new List<string> {"alpha@example.test"});

         var nonsense = Assert.Catch<Exception>(() => SetMembership(list, "everybody-in-sales"));
         StringAssert.Contains("The membership is empty", MessageChain(nonsense));

         var stranger = Assert.Catch<Exception>(() => SetMembership(list, "domain:nowhere.invalid"));
         StringAssert.Contains("which this server does not host", MessageChain(stranger));

         var bare = Assert.Catch<Exception>(() => SetMembership(list, "pattern:sales"));
         StringAssert.Contains("pattern: is followed by an address", MessageChain(bare));

         // And nothing of the three stuck.
         Assert.AreEqual("", GetMembership(list));
      }

      [Test]
      [Description("An accepted query is stored in its one canonical spelling")]
      public void AnAcceptedQueryIsStoredInItsCanonicalSpelling()
      {
         AddAccount("alpha@example.test");

         var list = CreateList("tidy@example.test", "  DOMAIN  ", new List<string>());

         Assert.AreEqual("domain", GetMembership(list));

         SetMembership(list, " Domain:Example.TEST ");
         list.Save();

         Assert.AreEqual("domain:example.test", GetMembership(list));

         // Read back through a fresh object, so this is the column rather than the
         // one in hand.
         var reread = _domain.DistributionLists.ItemByAddress["tidy@example.test"];
         Assert.AreEqual("domain:example.test", GetMembership(reread));

         // An empty membership is the off switch, and it leaves the rows alone.
         SetMembership(list, "");
         list.Save();

         Assert.AreEqual("", GetMembership(_domain.DistributionLists.ItemByAddress["tidy@example.test"]));

         CustomAsserts.AssertNoReportedError();
      }

      [Test]
      [Description("A query whose accounts cannot be read refuses the recipient with 451 rather than delivering to the list's rows and answering 250")]
      public void AQueryThatCannotBeAnsweredRefusesTheRecipientRatherThanDeliveringToTheRowsAlone()
      {
         var kept = AddAccount("kept@example.test");
         AddAccount("found@example.test");
         AddAccount("poster@example.test");

         // A list with BOTH a row and a query, which is the case the defect hid
         // in: the row expands, so the recipient looks resolvable, and the
         // temporary-failure guard - which only fires when NOTHING resolved -
         // never gets its chance. The message would be accepted for the one row
         // and lost for everybody the query would have answered, with the sender
         // told it arrived.
         CreateList("staff@example.test", "domain", new List<string> {kept.Address});

         // The one statement that reads a domain's accounts. The account lookup
         // the rest of the session makes is a different statement, so the
         // session is otherwise healthy and a 451 here can only have come from
         // the membership query.
         FailStatementsContaining("accountdomainid = @DOMAINID and accountactive");

         var socket = new TcpConnection();
         Assert.IsTrue(socket.Connect(TestPorts.Smtp));
         Assert.IsTrue(socket.Receive().StartsWith("220"));
         socket.SendAndReceive("HELO example.test\r\n");
         socket.SendAndReceive("MAIL FROM:<poster@example.test>\r\n");

         var refused = socket.SendAndReceive("RCPT TO:<staff@example.test>\r\n");

         // A plain account in the same domain is still accepted on the same
         // session: the server is not simply refusing everything.
         var accepted = socket.SendAndReceive("RCPT TO:<found@example.test>\r\n");

         socket.Disconnect();

         Assert.IsTrue(refused.StartsWith("451"),
            "A membership query that could not be answered must be a temporary failure the sender retries, not a 250 for the rows alone: " + refused);
         Assert.IsTrue(accepted.StartsWith("250"), accepted);

         // And nothing was delivered to the row, which is the half-delivery the
         // 451 exists to prevent.
         ImapClientSimulator.AssertMessageCount(kept.Address, Password, "Inbox", 0);

         CustomAsserts.AssertReportedError("HM6982");
      }

      [Test]
      [Description("A domain administrator may set a membership inside the domains it holds over COM and is refused one that reaches past them, as the REST create and update refuse the same forms")]
      public void ADomainAdministratorIsRefusedAMembershipThatReachesPastItsDomains()
      {
         var admin = AddAccount("listadmin@example.test");
         admin.AdminLevel = eAdminLevel.hAdminLevelDomainAdmin;
         admin.Save();

         SingletonProvider<TestSetup>.Instance.AddDomain("other.test");

         CreateList("confined@example.test", "", new List<string>());

         var asDomainAdmin = new Application();
         Assert.IsNotNull(asDomainAdmin.Authenticate(admin.Address, Password));

         var list = asDomainAdmin.Domains.ItemByName["example.test"]
            .DistributionLists.ItemByAddress["confined@example.test"];

         // Inside the one domain this administrator holds: allowed, and saved.
         SetMembership(list, "domain");
         list.Save();

         SetMembership(list, "pattern:sales-*@example.test");
         list.Save();

         // Past it. Each of these reaches accounts this administrator does not
         // administer - every domain, another tenant's, and a pattern whose
         // domain part is itself a wildcard - and each is refused before the
         // assignment takes, so nothing needs undoing.
         foreach (var reaching in new[] {"everyone", "domain:other.test", "pattern:*@*.test"})
         {
            var thrown = Assert.Catch<Exception>(() => SetMembership(list, reaching));
            StringAssert.Contains("outside the domains this administrator holds", MessageChain(thrown), reaching);
         }

         // Read back through the administrator's own object, so this is the
         // column rather than the one in hand: the query the domain
         // administrator was allowed to set, and none of the three refusals.
         Assert.AreEqual("pattern:sales-*@example.test",
            GetMembership(_domain.DistributionLists.ItemByAddress["confined@example.test"]));

         CustomAsserts.AssertNoReportedError();
      }

      [Test]
      [Description("A domain rename that would push a membership pattern past the 200 characters the column holds leaves the query as it is and says so, rather than letting the database decide half way through the rename")]
      public void ARenameThatWouldOverflowTheMembershipColumnLeavesTheQueryAlone()
      {
         AddAccount("alpha@example.test");

         var named = SingletonProvider<TestSetup>.Instance.AddDomain("ab.test");

         // Exactly the 200 characters the column holds: pattern: is 8, the
         // domain part 7, the @ one, and 184 for the rest.
         var query = "pattern:" + new string('a', 183) + "*@ab.test";
         Assert.AreEqual(200, query.Length);

         var list = CreateList("long@example.test", query, new List<string>());
         Assert.AreEqual(query, GetMembership(list));

         // Renaming the domain the pattern names to a longer one would rewrite
         // it to 219 characters. Nothing else measures that: a rename returns
         // early from the limitation check, which is the one place the length
         // is tested - so without the guard the database decides, either by
         // failing the insert after the domain, its accounts and its aliases
         // have already been renamed, or by silently shortening the query into
         // one nobody wrote.
         named.Name = "a-considerably-longer.test";
         named.Save();

         Assert.AreEqual(query, GetMembership(_domain.DistributionLists.ItemByAddress["long@example.test"]),
            "The query is left naming the old domain rather than written past the column.");

         CustomAsserts.AssertReportedError("HM6981");
      }
