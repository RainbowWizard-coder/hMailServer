      [Test]
      [Description("A record that carries another key never starts the propagation clock, however long it has been published.")]
      public void AWrongRecordNeverStartsThePropagationClock()
      {
         PrimaryKeyedDomain("old", false);
         Dictionary<string, object> staged = MiniJson.Object(_domain.DKIMRotationStart(""));

         var record = MiniJson.List(staged, "next.records").Cast<Dictionary<string, object>>().Single();
         string value = (string) record["value"];

         // The same key with one byte of its modulus changed: a well-formed record
         // that is not this key's.
         byte[] spki = Convert.FromBase64String(value.Substring("v=DKIM1; k=rsa; p=".Length));
         spki[100] ^= 0xFF;
         SuiteDns.Zone.WithTxt((string) record["host"], "v=DKIM1; k=rsa; p=" + Convert.ToBase64String(spki));

         Run(0);
         Run(30 * Day);

         Dictionary<string, object> status = Status(ReRead());
         Assert.AreEqual("different", MiniJson.Text(status, "next.check.status"));
         Assert.AreEqual(0, MiniJson.Number(status, "next.first_seen"), "A record carrying another key started the propagation clock.");
         Assert.AreEqual("old", ReRead().DKIMSelector);
      }

      [Test]
      [Description("The new key never signs before the switch; the switch happens after the propagation period from the first sighting and not an hour before; a message signed afterwards carries the new selector and verifies against the published record, and stops verifying once the record is gone.")]
      public void TheSwitchWaitsForThePropagationPeriodAndTheNewKeySignsWhatVerifies()
      {
         PrimaryKeyedDomain("old", true);
         Dictionary<string, object> staged = MiniJson.Object(_domain.DKIMRotationStart(""));
         string next = MiniJson.Text(staged, "next.selector");

         PublishRecordsOf(staged, "next");

         // Staged and published, but not switched: one signature, the old selector.
         string before = SendAndCapture();
         Assert.AreEqual(1, Regex.Matches(before, "DKIM-Signature", RegexOptions.IgnoreCase).Count, before);
         Assert.AreEqual("old", SelectorOfSignature(before), "The new key signed before the switch.\r\n" + before);

         Run(0);
         Dictionary<string, object> seen = Status(ReRead());
         Assert.AreEqual("propagating", MiniJson.Text(seen, "phase"));
         Assert.IsTrue(MiniJson.Number(seen, "next.first_seen") > 0, "The matching record was not recorded as seen.");

         Run(71 * Hour);
         Assert.AreEqual("old", ReRead().DKIMSelector, "Signing moved before the propagation period had passed.");

         Run(73 * Hour);
         Domain switched = ReRead();
         Assert.AreEqual(next, switched.DKIMSelector, "Signing did not move once the record had resolved for the propagation period.");
         Assert.AreEqual("", switched.DKIMSecondarySelector);
         Assert.AreEqual("", switched.DKIMSecondaryPrivateKeyFile);

         Dictionary<string, object> after = Status(switched);
         Assert.AreEqual(next, MiniJson.Text(after, "current.selector"));
         Assert.AreEqual("old", MiniJson.Text(after, "retiring.selector"), "The old selector is kept for late verifiers.");
         Assert.IsNull(MiniJson.At(after, "next"));

         // The message the domain sends now is signed with the new key...
         string signed = SendAndCapture();
         Assert.AreEqual(next, SelectorOfSignature(signed), "The message after the switch is not signed with the new selector.\r\n" + signed);

         string file = Paths.Combine(Path.GetTempPath(), "hmailserver-dkim-rotated-" + TestSetup.UniqueString() + ".eml");
         File.WriteAllText(file, signed);
         _filesToDelete.Add(file);

         // ...and verifies against the record the rotation told us to publish...
         Assert.AreEqual(eDKIMResult.eDKPass, _settings.AntiSpam.DKIMVerify(file),
            "The message signed after the switch does not verify against the published record.");

         // ...which is what makes it pass: without the record it cannot.
         SuiteDns.Reset();
         Assert.AreEqual(eDKIMResult.eDKPermFail, _settings.AntiSpam.DKIMVerify(file),
            "The verification passed without the record, so it proved nothing.");
      }

      [Test]
      [Description("A record that disappears before the switch sends the wait back to zero: seen again later, it must resolve for the whole propagation period again.")]
      public void ARecordThatDisappearsBeforeTheSwitchResetsTheWait()
      {
         PrimaryKeyedDomain("old", false);
         Dictionary<string, object> staged = MiniJson.Object(_domain.DKIMRotationStart(""));
         string next = MiniJson.Text(staged, "next.selector");

         PublishRecordsOf(staged, "next");
         Run(0);
         Assert.IsTrue(MiniJson.Number(Status(ReRead()), "next.first_seen") > 0, "The published record was not seen.");

         SuiteDns.Reset();
         Run(73 * Hour);

         Dictionary<string, object> gone = Status(ReRead());
         Assert.AreEqual("old", ReRead().DKIMSelector, "Signing moved to a key whose record had disappeared.");
         Assert.AreEqual(0, MiniJson.Number(gone, "next.first_seen"), "A record that disappeared kept its first sighting.");

         PublishRecordsOf(staged, "next");
         Run(74 * Hour);
         Run(145 * Hour);
         Assert.AreEqual("old", ReRead().DKIMSelector, "The wait did not start again from the second sighting.");

         Run(147 * Hour);
         Assert.AreEqual(next, ReRead().DKIMSelector, "The record seen again for the whole period was never switched to.");
      }

