      [Test]
      [Description("Rotate now puts a server-generated key under the DKIM directory, stages it as the secondary under a dated selector, and shows the TXT record to publish; the primary is not touched.")]
      public void RotateNowStagesAServerGeneratedKeyAndShowsTheRecordToPublish()
      {
         PrimaryKeyedDomain("old", false);

         Dictionary<string, object> status = MiniJson.Object(_domain.DKIMRotationStart(""));

         string selector = MiniJson.Text(status, "next.selector");
         StringAssert.IsMatch("^s[0-9]{8}$", selector, "The suggested selector is s and the UTC date.");
         Assert.IsTrue(MiniJson.Flag(status, "next.generated"), "The server generated this key, and says so.");

         string keyFile = MiniJson.Text(status, "next.key_file");
         string keyDirectory = Paths.Combine(_settings.Directories.DataDirectory, "DKIM");
         StringAssert.StartsWith(keyDirectory.TrimEnd('\\') + "\\", keyFile, "The key is kept under the data directory's DKIM directory.");
         Assert.IsTrue(File.Exists(keyFile), "The generated key file exists: " + keyFile);

         Dictionary<string, object> record = MiniJson.List(status, "next.records").Cast<Dictionary<string, object>>().Single();
         Assert.AreEqual(selector + "._domainkey.example.test", record["host"]);
         Assert.AreEqual("TXT", record["type"]);
         Assert.AreEqual("publish", record["action"]);

         string value = (string) record["value"];
         StringAssert.StartsWith("v=DKIM1; k=rsa; p=", value);

         // A 2048-bit RSA SubjectPublicKeyInfo is 294 bytes.
         byte[] spki = Convert.FromBase64String(value.Substring("v=DKIM1; k=rsa; p=".Length));
         Assert.AreEqual(294, spki.Length, "The record carries a 2048-bit RSA public key.");

         Assert.AreEqual("awaiting_dns", MiniJson.Text(status, "phase"));

         // The object this was called on carries the staged pair; the database agrees;
         // the primary is what it was.
         Assert.AreEqual(selector, _domain.DKIMSecondarySelector, "The COM object reads the staged selector back after the call.");
         Domain stored = ReRead();
         Assert.AreEqual(selector, stored.DKIMSecondarySelector);
         Assert.AreEqual(keyFile, stored.DKIMSecondaryPrivateKeyFile);
         Assert.AreEqual("old", stored.DKIMSelector, "Rotate now never moves signing.");

         // A second rotation while one is staged is refused, and so is a selector
         // that is not a DNS label or that would climb out of the key directory.
         var again = Assert.Throws<COMException>(() => _domain.DKIMRotationStart("another"));
         StringAssert.Contains("already staged", again.Message);

         _domain.DKIMRotationCancel();
         foreach (string bad in new[] { "../x", "a_b", "A/B", "a\\b" })
         {
            var refused = Assert.Throws<COMException>(() => _domain.DKIMRotationStart(bad), bad);
            StringAssert.Contains("selector must be", refused.Message, bad);
         }

         Assert.AreEqual("", ReRead().DKIMSecondarySelector, "No refused start staged anything.");
      }

