      [Test]
      [Description("A Domain object read before a switch, changed in an unrelated field and saved after it, is refused rather than allowed to put the old selector back; a fresh object saves.")]
      public void AStaleDomainSaveCannotUndoASwitch()
      {
         PrimaryKeyedDomain("old", false);
         Domain stale = ReRead();

         Dictionary<string, object> staged = MiniJson.Object(_domain.DKIMRotationStart(""));
         string next = MiniJson.Text(staged, "next.selector");
         PublishRecordsOf(staged, "next");
         Run(0);
         Run(73 * Hour);
         Assert.AreEqual(next, ReRead().DKIMSelector);

         stale.Postmaster = "stale@example.test";
         var refused = Assert.Throws<COMException>(() => stale.Save());
         StringAssert.Contains("managed by its key rotation", refused.Message);
         Assert.AreEqual(next, ReRead().DKIMSelector, "A stale save put the old selector back.");

         // The negative control: the same change from an object read now is fine.
         Domain fresh = ReRead();
         fresh.Postmaster = "fresh@example.test";
         fresh.Save();
         Assert.AreEqual("fresh@example.test", ReRead().Postmaster);
         Assert.AreEqual(next, ReRead().DKIMSelector);
      }

      [Test]
      [Description("The generated private key is readable by the server and the administrators and not by an ordinary user; a file written beside it by the test is readable, which is what proves the difference is the key's own permissions.")]
      public void TheGeneratedPrivateKeyIsReadableOnlyByTheServerAndAdministrators()
      {
         string keyFile = MiniJson.Text(MiniJson.Object(_domain.DKIMRotationStart("")), "next.key_file");
         Assert.IsTrue(File.Exists(keyFile));

         bool elevated = new WindowsPrincipal(WindowsIdentity.GetCurrent()).IsInRole(WindowsBuiltInRole.Administrator);

         if (elevated)
         {
            // An elevated test can read the security descriptor, so it reads it.
            FileSecurity security = new FileInfo(keyFile).GetAccessControl();
            Assert.IsTrue(security.AreAccessRulesProtected, "The key file inherits its directory's permissions.");

            var everyone = new SecurityIdentifier(WellKnownSidType.WorldSid, null);
            var users = new SecurityIdentifier(WellKnownSidType.BuiltinUsersSid, null);
            var authenticated = new SecurityIdentifier(WellKnownSidType.AuthenticatedUserSid, null);

            foreach (FileSystemAccessRule rule in security.GetAccessRules(true, true, typeof(SecurityIdentifier)))
            {
               Assert.IsFalse(rule.IdentityReference.Equals(everyone) || rule.IdentityReference.Equals(users) || rule.IdentityReference.Equals(authenticated),
                  "The key file grants " + rule.IdentityReference + " " + rule.FileSystemRights);
            }
         }
         else
         {
            Assert.Throws<UnauthorizedAccessException>(() => File.ReadAllText(keyFile),
               "An unelevated user read the generated private key.");
         }

         // The control: the directory itself does not refuse this user.
         string beside = Paths.Combine(Path.GetDirectoryName(keyFile), "control-" + TestSetup.UniqueString() + ".txt");
         try
         {
            File.WriteAllText(beside, "control");
         }
         catch (UnauthorizedAccessException)
         {
            Assert.Inconclusive("The test cannot write into " + Path.GetDirectoryName(keyFile) + ", so the control cannot be made.");
         }

         _filesToDelete.Add(beside);
         Assert.AreEqual("control", File.ReadAllText(beside), "A file written beside the key could not be read back.");

         if (elevated)
            Assert.IsFalse(new FileInfo(beside).GetAccessControl().AreAccessRulesProtected, "The control file does not inherit, so it controls for nothing.");
      }

      [Test]
      [Description("Deleting a domain removes the key files its rotation generated and leaves a key file the administrator supplied.")]
      public void DeletingADomainRemovesTheKeysItsRotationGenerated()
      {
         Domain doomed = SingletonProvider<TestSetup>.Instance.AddDomain("rotation-delete.test");
         string handKey = HandSuppliedKey();
         doomed.DKIMSelector = "old";
         doomed.DKIMPrivateKeyFile = handKey;
         doomed.Save();

         string generated = MiniJson.Text(MiniJson.Object(doomed.DKIMRotationStart("")), "next.key_file");
