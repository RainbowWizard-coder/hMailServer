      [Test]
      [Description("A key the rotation generated is kept for the retention period after it stops signing and then retired: its file is deleted and the status says its record may be removed.")]
      public void TheOldSelectorIsKeptForTheRetentionPeriodAndThenRetired()
      {
         // A domain with no key at all: the first rotation gives it one, and the
         // second makes that generated key the one that retires.
         Dictionary<string, object> first = MiniJson.Object(_domain.DKIMRotationStart("first"));
         string firstKey = MiniJson.Text(first, "next.key_file");
         PublishRecordsOf(first, "next");
         Run(0);
         Run(73 * Hour);
         Assert.AreEqual("first", ReRead().DKIMSelector);
         Assert.IsNull(MiniJson.At(Status(ReRead()), "retiring"), "The first key replaced nothing, so nothing retires.");

         Dictionary<string, object> second = MiniJson.Object(ReRead().DKIMRotationStart("second"));
         PublishRecordsOf(second, "next");
         Run(80 * Hour);
         Run(153 * Hour);
         Assert.AreEqual("second", ReRead().DKIMSelector);

         Dictionary<string, object> retiring = Status(ReRead());
         Assert.AreEqual("first", MiniJson.Text(retiring, "retiring.selector"));
         Assert.IsTrue(MiniJson.Flag(retiring, "retiring.generated"));

         Run(153 * Hour + 6 * Day);
         Assert.AreEqual("first", MiniJson.Text(Status(ReRead()), "retiring.selector"), "Retired before the retention period ended.");
         Assert.IsTrue(File.Exists(firstKey), "The retiring key file was removed before the retention period ended.");

         Run(153 * Hour + 7 * Day + Hour);
         Dictionary<string, object> retired = Status(ReRead());
         Assert.IsNull(MiniJson.At(retired, "retiring"));
         Assert.AreEqual("first", MiniJson.Text(retired, "retired.selector"));
         Assert.AreEqual("", MiniJson.Text(retired, "retired.key_file_kept"));

         var removal = MiniJson.List(retired, "retired.records").Cast<Dictionary<string, object>>().Single();
         Assert.AreEqual("first._domainkey.example.test", removal["host"]);
         Assert.AreEqual("remove", removal["action"]);

         Assert.IsFalse(File.Exists(firstKey), "The generated key file was not deleted when its selector retired.");
         Assert.AreEqual("second", ReRead().DKIMSelector);
      }

