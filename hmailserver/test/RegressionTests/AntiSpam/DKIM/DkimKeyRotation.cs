      [Test]
      [Description("The policy's periods and key size are refused out of range over COM, each with nothing changed; in range they persist.")]
      public void PolicyValuesOutOfRangeAreRefusedOverCom()
      {
         Assert.Throws<COMException>(() => _domain.DKIMRotationIntervalDays = 0);
         Assert.Throws<COMException>(() => _domain.DKIMRotationIntervalDays = 3651);
         Assert.Throws<COMException>(() => _domain.DKIMRotationPropagationHours = 721);
         Assert.Throws<COMException>(() => _domain.DKIMRotationPropagationHours = 0);
         Assert.Throws<COMException>(() => _domain.DKIMRotationRetentionDays = 0);
         Assert.Throws<COMException>(() => _domain.DKIMRotationKeyBits = 1024);
         Assert.Throws<COMException>(() => _domain.DKIMRotationKeyBits = 3000);

         Assert.AreEqual(180, _domain.DKIMRotationIntervalDays, "The shipped interval.");
         Assert.AreEqual(72, _domain.DKIMRotationPropagationHours, "The shipped propagation period.");
         Assert.AreEqual(7, _domain.DKIMRotationRetentionDays, "The shipped retention period.");
         Assert.AreEqual(2048, _domain.DKIMRotationKeyBits, "The shipped key size.");
         Assert.IsFalse(_domain.DKIMRotationEnabled, "The schedule ships off.");

         _domain.DKIMRotationEnabled = true;
         _domain.DKIMRotationIntervalDays = 90;
         _domain.DKIMRotationPropagationHours = 48;
         _domain.DKIMRotationRetentionDays = 14;
         _domain.DKIMRotationKeyBits = 3072;
         _domain.Save();

         Domain stored = ReRead();
         Assert.IsTrue(stored.DKIMRotationEnabled);
         Assert.AreEqual(90, stored.DKIMRotationIntervalDays);
         Assert.AreEqual(48, stored.DKIMRotationPropagationHours);
         Assert.AreEqual(14, stored.DKIMRotationRetentionDays);
         Assert.AreEqual(3072, stored.DKIMRotationKeyBits);

         // Switched off again before the fixture's next domain inherits nothing -
         // the domain is recreated by the next SetUp, but a scheduled pass in between
         // would give a keyless domain with the schedule on its first key.
         stored.DKIMRotationEnabled = false;
         stored.Save();

         var ex = Assert.Throws<COMException>(() => _application.Utilities.RunDkimRotation(-1));
         StringAssert.Contains("SecondsAhead", ex.Message);
      }
