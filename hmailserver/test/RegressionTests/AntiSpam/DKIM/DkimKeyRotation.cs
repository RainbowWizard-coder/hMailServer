   /// <summary>
   ///    DKIM keys that rotate, over COM: a key generated by the server, its record
   ///    checked from the server's own resolver against the suite's DNS zone, signing
   ///    moved to it only after the record has resolved for the propagation period,
   ///    the old selector kept for the retention period and then retired.
   ///
   ///    Nothing here waits. Utilities.RunDkimRotation runs one pass of the rotation
   ///    with the clock moved forward for that pass, so seventy-three hours and a week
   ///    are two calls. A pass with the real clock may run in the background at any
   ///    moment - the scheduled task is always on - and the rotation's engine serialises
   ///    it with these: a first sighting it records is earlier than the test's, never
   ///    later, so nothing below depends on which of the two looked first.
   ///
   ///    The tests that could pass without the feature working carry their negative
   ///    control: the switch test has the missing-record test beside it, the
   ///    verification after the switch fails once the record is taken away, and the
   ///    permission test writes a file of its own beside the key.
   /// </summary>
   [TestFixture]
   public class DkimKeyRotation : TestFixtureBase
   {
      private const int Hour = 3600;
      private const int Day = 86400;

      // The capture listener for the delivery tests. Allocated to this row.
      private const int CapturePort = 9552;

      private readonly List<string> _filesToDelete = new List<string>();

      private bool _senderAdded;

      [TearDown]
      public void ForgetTheZoneAndTheFiles()
      {
         SuiteDns.Reset();

         foreach (string file in _filesToDelete)
         {
            try
            {
               if (File.Exists(file))
                  File.Delete(file);
            }
            catch (IOException)
            {
            }
            catch (UnauthorizedAccessException)
            {
            }
         }

         _filesToDelete.Clear();
         _senderAdded = false;
      }

      // ------------------------------------------------------------------ helpers

      /// <summary>
      ///    A private key supplied by hand, as the Control Panel's generator or an
      ///    administrator would supply one: the suite's example key, written afresh so
      ///    that the file is as old as this test - a key adopted into a rotation is as
      ///    old as its file, and the checkout's example key may be years old.
      /// </summary>
      private string HandSuppliedKey()
      {
         string source = Paths.Combine(TestContext.CurrentContext.TestDirectory, "..\\..\\..\\..\\SSL examples", "example.key");
         Assert.IsTrue(File.Exists(source), "The example key file could not be found at " + source);

         string copy = Paths.Combine(Path.GetTempPath(), "hmailserver-dkim-hand-" + TestSetup.UniqueString() + ".key");
         File.WriteAllText(copy, File.ReadAllText(source));
         _filesToDelete.Add(copy);
         return copy;
      }

      private Domain ReRead(string name = "example.test")
      {
         return _application.Domains.get_ItemByName(name);
      }

      private static Dictionary<string, object> Status(Domain domain)
      {
         return MiniJson.Object(domain.DKIMRotationStatus);
      }

      private string Run(int secondsAhead)
      {
         return _application.Utilities.RunDkimRotation(secondsAhead);
      }

      private static void PublishRecordsOf(Dictionary<string, object> status, string slot)
      {
         List<object> records = MiniJson.List(status, slot + ".records");
         Assert.IsTrue(records.Count > 0, "The status names no record for " + slot + ".");

         foreach (Dictionary<string, object> record in records.Cast<Dictionary<string, object>>())
            SuiteDns.Zone.WithTxt((string) record["host"], (string) record["value"]);
      }

      private Domain PrimaryKeyedDomain(string selector, bool signingEnabled)
      {
         _domain.DKIMSelector = selector;
         _domain.DKIMPrivateKeyFile = HandSuppliedKey();
         _domain.DKIMSignEnabled = signingEnabled;
         _domain.Save();
         return _domain;
      }

      /// <summary>Sends one message from the domain and returns it as the far side received it.</summary>
      private string SendAndCapture()
      {
         if (!_senderAdded)
         {
            SingletonProvider<TestSetup>.Instance.AddAccount(_domain, "test@example.test", "test");
            _senderAdded = true;
         }

         var deliveryResults = new Dictionary<string, int> { { "test@example.com", 250 } };

         using (var server = new SmtpServerSimulator(1, CapturePort))
         {
            server.SecondsToWaitBeforeTerminate = 60;
            server.AddRecipientResult(deliveryResults);
            server.StartListen();

            Route route = Signing.AddRoutePointingAtLocalhost(5, CapturePort);
            try
            {
               var smtp = new SmtpClientSimulator();
               smtp.Send("test@example.test", new List<string> { "test@example.com" }, "Rotation", "A message signed during a key rotation.");

               server.WaitForCompletion();
               CustomAsserts.AssertRecipientsInDeliveryQueue(0);
               return server.MessageData;
            }
            finally
            {
               _settings.Routes.DeleteByDBID(route.ID);
            }
         }
      }

      private static string SelectorOfSignature(string messageData)
      {
         Match match = Regex.Match(messageData, @"DKIM-Signature:[\s\S]*?\bs=([a-z0-9.\-]+)", RegexOptions.IgnoreCase);
         return match.Success ? match.Groups[1].Value : null;
      }

