"""Every setting the server reads from hMailServer.INI can be set from the Control Panel.

An INI setting with no editor is not a small omission. It is invisible to a
Control Panel connected to another machine, it does not appear in the settings
search, and the only way to change it is to open a text file on the server -
which is the thing the Control Panel exists to avoid. The gap is also silent:
nothing fails, the setting simply cannot be found, and the person looking for it
concludes the feature does not exist.

Three checks, all driven off the server's own source rather than a list kept by
hand:

  coverage  Every key `IniFileSettings` reads from [Settings] is named somewhere
            in the Control Panel's source. EXEMPT below is the list of keys that
            deliberately have no editor, each with the reason; anything else
            missing fails.

  frozen    The rule since 15 September 2026, in .github/CONTRIBUTING.md: a
            SETTING BELONGS IN THE DATABASE, and no key is added to [Settings].
            build/ini-settings-baseline.txt is every key the server read from the
            file on the day the database became the settings store; a key that
            appears in [Settings] and is not in it fails here. The bootstrap
            sections - [Directories], [Database], [Security] and [GUILanguages],
            which are read before the database is open - can still gain a key, by
            adding it to the baseline in the same commit and saying why in the
            commit message. --write-baseline regenerates the file for the one case
            where a key is legitimately REMOVED.

  mirrored  Every INI key the server reads is read THROUGH IniFileSettings, so
            that the settings store sees it. A key read with its own profile call
            is absent from the stored values, from backup and restore, and from
            the COM settings API - so it cannot be administered remotely at all.
            OUTSIDE below records the sections that are known to do this, so that
            a NEW one fails here. The seam itself is two files - IniFileSettings
            and IniSettingStore, the only class that touches the file as a file -
            and neither can be outside itself, so both are skipped.

  listed    Common/Application/IniSettingsBaseline.h holds the [Settings] keys of
            the baseline as a C++ array, so that the server itself knows which
            names it reads: `hmailserver --set-setting NAME=VALUE` refuses any
            other name, because storing it would change nothing. The header is
            generated by --write-baseline beside the text file, and this check
            fails when the two differ.

  defaults  The baseline carries each key's SHIPPED DEFAULT - the third argument
            of the read in IniFileSettings.cpp - and the kind of read it is, and
            the header carries them into the binary. That is what lets the server
            answer "which settings are not what this version ships with", which is
            /api/v1/settings/changed, Settings.GetChangedFromDefault over COM,
            `hmctl config changed` and the Deck's Changed from stock page. A
            default edited in the source and not regenerated here fails this
            check, because a list of what has been changed that compares against
            last month's defaults is worse than no list: it is confidently wrong.

Exits 1 listing what is missing.
"""
import json
import os
import re
import sys

BASELINE = os.path.join(os.path.dirname(os.path.abspath(__file__)), "ini-settings-baseline.txt")

# The same [Settings] keys as a C++ header, so that the server knows at run time
# which names it reads: `hmailserver --set-setting NAME=VALUE` refuses a name
# that is not one of them, since storing it would change nothing. Generated by
# --write-baseline beside the text file and held to it by the `listed` check
# below, so the two cannot drift.
BASELINE_HEADER = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
                               "hmailserver", "source", "Server", "Common", "Application", "IniSettingsBaseline.h")

# The sections that are read before the database is open, and are therefore the
# only place a genuinely pre-database key can go. [Settings] is not one of them:
# it is the section the store moved out of.
BOOTSTRAP = ("Directories", "Database", "Security", "GUILanguages")

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SERVER = os.path.join(ROOT, "hmailserver", "source", "Server")
INI_FILE = os.path.join(SERVER, "Common", "Application", "IniFileSettings.cpp")
CONTROL_PANEL = os.path.join(ROOT, "hmailserver", "source", "Tools", "ControlPanel")

# A [Settings] key with no editor, and why. A key belongs here only when an
# editor would be wrong - not when one has not been written yet.
EXEMPT = {
   "SimulateDatabaseFailureFor":
      "A fault-injection switch for the regression suite. An editor would offer an "
      "administrator a way to break their own server on purpose.",
   "SimulateSpoolWriteFailure":
      "A fault-injection switch for the regression suite, as above.",
}

# Sections read outside IniFileSettings today. Each is a gap - it is invisible to
# the database mirror - and each is recorded here so that the number cannot grow
# without somebody deciding to let it.
OUTSIDE = {
   "LDAP": "LdapSettings.cpp reads the directory settings directly.",
   "SendingLimits": "RateLimiter reads the per-account limits directly.",
   "SendingLimitsOverrides": "A free-form section: one line per address, so it has no fixed key set.",
}

READ = re.compile(r'ReadIniSetting(String|Integer)_\s*\(')
# The three password work factors are read through a helper that bounds them,
# which is the one reader that does not name its section: the section is
# [Settings] and the default it passes on is 0, which means "the built-in work
# factor" and is what an unchanged server has.
WORK_FACTOR = re.compile(r'ReadPasswordHashWorkFactor_\s*\(\s*(?:_T\()?"([A-Za-z0-9]+)"')
# A profile call outside IniFileSettings: the Windows API, or our own wrapper.
PROFILE = re.compile(r'GetPrivateProfile(?:String|Int)W?\s*\(\s*_?T?\(?"([A-Za-z]+)"')
# A C++ string literal, with or without the _T() around it.
LITERAL = re.compile(r'^(?:_T\()?"((?:[^"\\]|\\.)*)"\)?$', re.S)


def read(path):
   with open(path, "r", encoding="utf-8", errors="replace") as handle:
      return handle.read()


def call_arguments(text, open_paren):
   """The top-level arguments of the call whose '(' is at open_paren.

   A regular expression cannot do this: a default is an expression and may carry
   its own brackets and its own commas (_T("a,b") and ClampTo(x, y) both occur in
   this file's history), and reading a default wrongly is worse than not reading
   it, because the answer would be a setting reported as changed that is not."""
   depth = 0
   index = open_paren
   start = open_paren + 1
   arguments = []
   in_string = False
   while index < len(text):
      char = text[index]
      if in_string:
         if char == "\\":
            index += 2
            continue
         if char == '"':
            in_string = False
      elif char == '"':
         in_string = True
      elif char == "(":
         depth += 1
      elif char == ")":
         depth -= 1
         if depth == 0:
            arguments.append(text[start:index])
            return arguments
      elif char == "," and depth == 1:
         arguments.append(text[start:index])
         start = index + 1
      index += 1
   return None


def literal(text):
   """The text of a C++ string literal, or None when the argument is not one."""
   match = LITERAL.match(text.strip())
   if not match:
      return None
   return re.sub(r"\\(.)", lambda m: {"n": "\n", "t": "\t", "r": "\r"}.get(m.group(1), m.group(1)), match.group(1))


NUMBER = re.compile(r"^-?\d+$")


def reads_of(source):
   """Every setting the server reads, as {(section, key): (kind, default)}, and
   the reads whose default this cannot make out.

   kind is "integer" where the read is ReadIniSettingInteger_ and "string" where
   it is ReadIniSettingString_, and it decides how a stored value is compared
   with the default: the integer read is GetPrivateProfileInt, which stops at the
   first character that is not part of a number, so "9" and "0009" are the same
   setting and only a string read would call them different.

   A default that is neither a string literal nor a decimal number - a constant,
   a call, an expression - is reported rather than guessed at. Writing the source
   text into the baseline would put a C++ identifier where a value belongs, and
   every installation would then be told that setting had been changed."""
   found = {}
   unreadable = []
   for match in READ.finditer(source):
      arguments = call_arguments(source, match.end() - 1)
      if arguments is None or len(arguments) != 3:
         continue
      section = literal(arguments[0])
      key = literal(arguments[1])
      if section is None or key is None:
         # The two reads whose section or key is a variable: the work-factor
         # helper below, and GetSettingsValue, which reads a name given to it.
         continue
      kind = "integer" if match.group(1) == "Integer" else "string"
      text = arguments[2].strip()
      value = literal(text)
      if value is None and kind == "integer" and NUMBER.match(text):
         value = text
      if value is None:
         unreadable.append((section, key, " ".join(text.split())))
         continue
      found[(section, key)] = (kind, value)

   for match in WORK_FACTOR.finditer(source):
      found[("Settings", match.group(1))] = ("integer", "0")

   return found, unreadable


def control_panel_text():
   parts = []
   for base, _, names in os.walk(CONTROL_PANEL):
      if os.sep + "obj" in base or os.sep + "bin" in base:
         continue
      for name in names:
         if name.endswith((".cs", ".xaml")):
            parts.append(read(os.path.join(base, name)))
   return "\n".join(parts)


def read_baseline():
   """The committed baseline, as {(section, key): (kind, default)}.

   Four fields to a line - section, key, kind, default - with the default JSON
   encoded, so that an empty one is a token rather than a missing column and one
   that ever holds a space, a quote or a character outside ASCII survives the
   round trip."""
   pairs = {}
   if not os.path.exists(BASELINE):
      return None
   for line in read(BASELINE).splitlines():
      line = line.strip()
      if not line or line.startswith("#"):
         continue
      parts = line.split(None, 3)
      if len(parts) != 4:
         continue
      try:
         value = json.loads(parts[3])
      except ValueError:
         continue
      pairs[(parts[0], parts[1])] = (parts[2], value)
   return pairs


def write_baseline(pairs):
   """Rewrites the baseline, keeping the explanation at the top of the file."""
   header = []
   if os.path.exists(BASELINE):
      for line in read(BASELINE).splitlines():
         if line.startswith("#") or not line.strip():
            header.append(line)
         else:
            break
      while header and not header[-1].strip():
         header.pop()

   lines = list(header)
   section = None
   for (this_section, key) in sorted(pairs):
      if this_section != section:
         lines.append("")
         section = this_section
      kind, value = pairs[(this_section, key)]
      lines.append("%s %s %s %s" % (this_section, key, kind, json.dumps(value)))

   with open(BASELINE, "w", encoding="utf-8", newline="\r\n") as handle:
      handle.write("\n".join(lines) + "\n")

   print("Wrote %s: %d key(s)." % (os.path.basename(BASELINE), len(pairs)))

   write_baseline_header(pairs)


HEADER_ROW = re.compile(r'\{\s*_T\("((?:[^"\\]|\\.)*)"\),\s*_T\("((?:[^"\\]|\\.)*)"\),\s*(true|false)\s*\}')


def cpp_literal(value):
   """A C++ string literal's insides. Only the two characters that would end it
   or start an escape can occur in a default, and both are escaped rather than
   refused, because a default is whatever the source says it is."""
   return value.replace("\\", "\\\\").replace('"', '\\"')


def baseline_header_text(settings):
   """The header, from the [Settings] keys alone: the bootstrap sections are read
   from the file before the database is open and are nobody's to store."""
   lines = [
      "// https://www.progressiverobot.com",
      "// Copyright (c) 2026 Christopher Holloway / Progressive Robot Ltd",
      "// SPDX-License-Identifier: AGPL-3.0-or-later",
      "",
      "// GENERATED by build/check-ini-coverage.py --write-baseline from",
      "// build/ini-settings-baseline.txt, and held to it by that check on every pull",
      "// request. Do not edit: change what IniFileSettings reads, regenerate both.",
      "//",
      "// Every [Settings] key the server reads through IniFileSettings, with the",
      "// default it reads it with and whether it reads it as a number, as a C++ array,",
      "// so that the server knows the list at run time. Two things consult it:",
      "//",
      "//   IniSettingStore::IsSettingTheServerReads, for `hmailserver --set-setting",
      "//   NAME=VALUE`, which refuses a name that is not here because storing it would",
      "//   change nothing - the REST API and COM store any name, for a setting a script",
      "//   of the administrator's own reads, and stay that way.",
      "//",
      "//   SettingsDiff, which answers which of this server's settings are not what",
      "//   this version ships with. Default is the third argument of the read, as it",
      "//   stands in the source; IsInteger says the read is GetPrivateProfileInt, which",
      "//   stops at the first character that is not part of a number, so a stored",
      "//   \"0009\" is the same setting as a default of 9 and is not a difference.",
      "",
      "#pragma once",
      "",
      "namespace HM",
      "{",
      "   namespace IniSettingsBaseline",
      "   {",
      "      struct Setting",
      "      {",
      "         const TCHAR *Name;",
      "         const TCHAR *Default;",
      "         bool IsInteger;",
      "      };",
      "",
      "      static const Setting Settings[] =",
      "      {",
   ]
   for key, kind, value in settings:
      lines.append('         { _T("%s"), _T("%s"), %s },'
                   % (cpp_literal(key), cpp_literal(value), "true" if kind == "integer" else "false"))
   lines += [
      "      };",
      "",
      "      static const size_t SettingsCount = sizeof(Settings) / sizeof(Settings[0]);",
      "   }",
      "}",
   ]
   return "\n".join(lines) + "\n"


def baseline_settings(pairs):
   """The [Settings] rows of a baseline, as (key, kind, default), sorted by key."""
   return sorted((key, pairs[(section, key)][0], pairs[(section, key)][1])
                 for (section, key) in pairs if section == "Settings")


def write_baseline_header(pairs):
   settings = baseline_settings(pairs)
   with open(BASELINE_HEADER, "w", encoding="utf-8", newline="\r\n") as handle:
      handle.write(baseline_header_text(settings))
   print("Wrote %s: %d [Settings] key(s)." % (os.path.basename(BASELINE_HEADER), len(settings)))


def check_baseline_header(baseline):
   """The keys the header carries, against the baseline's [Settings] keys."""
   expected = baseline_settings(baseline)
   if not os.path.exists(BASELINE_HEADER):
      return ["  %s is missing; run python3 build/check-ini-coverage.py --write-baseline"
              % os.path.relpath(BASELINE_HEADER, ROOT)]
   found = [(name, "integer" if integer == "true" else "string", value)
            for name, value, integer in HEADER_ROW.findall(read(BASELINE_HEADER))]
   if found == expected:
      return []
   problems = []
   found_by_name = dict((row[0], row) for row in found)
   expected_by_name = dict((row[0], row) for row in expected)
   for key in sorted(set(expected_by_name) - set(found_by_name)):
      problems.append("  [Settings] %s is in the baseline but not in %s" % (key, os.path.basename(BASELINE_HEADER)))
   for key in sorted(set(found_by_name) - set(expected_by_name)):
      problems.append("  %s lists [Settings] %s, which is not in the baseline" % (os.path.basename(BASELINE_HEADER), key))
   for key in sorted(set(expected_by_name) & set(found_by_name)):
      if expected_by_name[key] != found_by_name[key]:
         problems.append("  [Settings] %s is %r in the baseline and %r in %s"
                         % (key, expected_by_name[key][1:], found_by_name[key][1:], os.path.basename(BASELINE_HEADER)))
   if not problems:
      problems.append("  %s lists the baseline's keys in a different order or more than once" % os.path.basename(BASELINE_HEADER))
   problems.append("  run python3 build/check-ini-coverage.py --write-baseline to regenerate the header from the baseline")
   return problems


def main():
   if not os.path.exists(INI_FILE):
      print("IniFileSettings.cpp not found at %s" % INI_FILE)
      return 1

   source = read(INI_FILE)
   present, unreadable = reads_of(source)
   by_section = {}
   for section, key in present:
      by_section.setdefault(section, set()).add(key)

   if "--write-baseline" in sys.argv:
      if unreadable:
         for section, key, text in unreadable:
            print("  [%s] %s is read with the default `%s`, which is not a literal value. "
                  "The baseline holds values, not expressions: give the read a literal "
                  "default, or teach reads_of() to work this one out." % (section, key, text))
         print("FAIL: nothing was written.")
         return 1
      write_baseline(present)
      return 0

   baseline = read_baseline()
   frozen = []

   for section, key, text in unreadable:
      frozen.append(
         "  [%s] %s is read with the default `%s`, which is not a literal value, so this "
         "check cannot record what an unchanged server has for it. Give the read a literal "
         "default, or teach reads_of() to work this one out." % (section, key, text))

   if baseline is None:
      frozen.append("  the baseline %s is missing, so nothing is holding the rule that "
                    "a setting goes in the database" % os.path.basename(BASELINE))
      baseline = present

   for section, key in sorted(set(present) - set(baseline)):
      if section == "Settings":
         frozen.append(
            "  [Settings] %s is new. A SETTING BELONGS IN THE DATABASE: put it in "
            "hm_settings, reached through Property and PropertySet, and give it a Control "
            "Panel editor - .github/CONTRIBUTING.md says so and this check is what holds "
            "it. The [Settings] section is a cache of hm_inisettings now, not a store, so a "
            "key added here is a setting nobody can administer remotely, that no backup "
            "carries and that two nodes cannot share." % key)
      elif section in BOOTSTRAP:
         frozen.append(
            "  [%s] %s is new. That section is read before the database is open, so a key "
            "there is allowed - but it is meant to be rare: add it to %s in this same "
            "commit and say in the commit message why it cannot wait for the database."
            % (section, key, os.path.basename(BASELINE)))
      else:
         frozen.append(
            "  [%s] %s is new, and [%s] is not one of the sections that are read before the "
            "database is open. A setting belongs in hm_settings; a bootstrap key belongs in "
            "[Directories], [Database] or [Security]." % (section, key, section))

   for section, key in sorted(set(baseline) - set(present)):
      frozen.append(
         "  [%s] %s is in %s but the server no longer reads it. Removing a setting from the "
         "file is the direction this is going: delete the line in the same commit, or run "
         "python3 build/check-ini-coverage.py --write-baseline."
         % (section, key, os.path.basename(BASELINE)))

   # The shipped default, which is the whole point of the list of what an
   # installation has changed. A default edited in the source and not regenerated
   # here would make that list quietly wrong - a setting reported as changed that
   # is not, or, worse, one left out that is - so it fails rather than drifts.
   for section, key in sorted(set(baseline) & set(present)):
      if baseline[(section, key)] != present[(section, key)]:
         was_kind, was_value = baseline[(section, key)]
         now_kind, now_value = present[(section, key)]
         frozen.append(
            "  [%s] %s is read as %s with the default %r, and %s says %s with %r. The default "
            "is what /api/v1/settings/changed, Settings.GetChangedFromDefault, `hmctl config "
            "changed` and the Deck compare an installation against: run python3 "
            "build/check-ini-coverage.py --write-baseline in the same commit as the change."
            % (section, key, now_kind, now_value, os.path.basename(BASELINE), was_kind, was_value))

   frozen.extend(check_baseline_header(baseline))

   settings = sorted(by_section.get("Settings", ()))
   if not settings:
      print("No [Settings] keys found - has IniFileSettings.cpp changed shape?")
      return 1

   panel = control_panel_text()
   # A key counts as reachable when the Control Panel names it anywhere: as the
   # key of an INI-backed editor, or in the help text beside a COM-backed one.
   # Several settings are stored in the INI but edited through a COM property
   # under a different name - the recipient tarpit is SmtpTarpitCount in the file
   # and AntiSpam.TarpitCount on the object - and the card that edits those says
   # so in its own words. Requiring the quoted key would call those missing.
   missing = [key for key in settings
              if key not in EXEMPT and not re.search(r"\b%s\b" % re.escape(key), panel)]

   # Anything reading the INI directly, other than IniFileSettings itself.
   direct = {}
   for base, _, names in os.walk(SERVER):
      if os.sep + "x64" in base:
         continue
      for name in names:
         # The seam itself is two files: IniFileSettings, which every reader goes
         # through, and IniSettingStore behind it, which is the only thing that
         # reads or writes the file as a file. Neither can be "outside" itself.
         if not name.endswith((".cpp", ".h")) or name.startswith(("IniFileSettings", "IniSettingStore")):
            continue
         path = os.path.join(base, name)
         for section in PROFILE.findall(read(path)):
            if section not in OUTSIDE:
               direct.setdefault(section, set()).add(os.path.relpath(path, ROOT))

   for key in missing:
      print("  no Control Panel editor: [Settings] %s" % key)
   for line in frozen:
      print(line)
   for section, files in sorted(direct.items()):
      print("  [%s] is read outside IniFileSettings, so the settings store never "
            "sees it: %s" % (section, ", ".join(sorted(files))))

   problems = len(missing) + len(frozen) + len(direct)
   if problems:
      print("FAIL: %d problem(s) with the settings the server reads from hMailServer.INI" % problems)
      return 1

   print("OK    all %d [Settings] keys have a Control Panel editor (%d exempt), the %d key(s) "
         "in the baseline are exactly the keys the server reads with exactly the defaults it "
         "reads them with, and every section is read through IniFileSettings"
         % (len(settings), len(EXEMPT), len(baseline)))
   return 0


if __name__ == "__main__":
   sys.exit(main())
